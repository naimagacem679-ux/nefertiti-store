#!/usr/bin/env python3
"""Phase 1 data migration: reads the ORIGINAL store data (read-only) and writes
   db/seed.sql  +  seed-images/*  (data-URI images extracted to files for R2).
   Usage: python3 -I scripts/make_seed.py   (run from the project root)
   It never modifies db/source/* or public/index.html."""
import base64, hashlib, json, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "db", "source")
D = json.load(open(os.path.join(SRC, "store-data.original.json"), encoding="utf8"))
WIL = json.load(open(os.path.join(SRC, "wilayas.json"), encoding="utf8"))
IMG_DIR = os.path.join(ROOT, "seed-images")
os.makedirs(IMG_DIR, exist_ok=True)

EXT = {"jpeg": "jpg", "jpg": "jpg", "png": "png", "webp": "webp", "gif": "gif"}
saved = {}  # key -> file name


def img_key(value, label):
    """data URI -> file in seed-images, returns the R2 key ('' if empty). Plain URLs are kept as-is."""
    if not value:
        return ""
    m = re.match(r"data:image/([a-zA-Z+]+);base64,(.*)$", value, re.S)
    if not m:
        return value
    raw = base64.b64decode(m.group(2))
    ext = EXT.get(m.group(1).lower(), "bin")
    key = f"{label}-{hashlib.sha256(raw).hexdigest()[:10]}.{ext}"
    if key not in saved:
        open(os.path.join(IMG_DIR, key), "wb").write(raw)
        saved[key] = len(raw)
    return key


def q(v):
    if v is None:
        return "NULL"
    if isinstance(v, bool):
        return "1" if v else "0"
    if isinstance(v, (int, float)):
        return str(int(v)) if float(v).is_integer() else str(v)
    return "'" + str(v).replace("'", "''") + "'"


def js(v):
    return q(json.dumps(v, ensure_ascii=False, separators=(",", ":")))


out = ["-- Generated by scripts/make_seed.py from db/source/store-data.original.json. Do not edit by hand.",
       "PRAGMA foreign_keys = ON;", ""]
st = D["store"]

# settings (images become R2 keys)
settings = {
    "name": st["name"], "sub2": st.get("sub2", ""), "slogan": st.get("slogan", ""),
    "whatsapp": st["whatsapp"], "currency": st.get("currency", "دج"), "free_over": str(st.get("freeOver", "0")),
    "contact_note": st.get("contactNote", ""), "logo_key": img_key(st.get("logo", ""), "logo"),
    "banner_key": img_key(st.get("banner", ""), "banner"),
    "page_about": (st.get("pages") or {}).get("about", ""), "page_email": (st.get("pages") or {}).get("email", ""),
    "data_version": D.get("v", 3),
}
for k, v in settings.items():
    out.append(f"INSERT INTO settings(key,value) VALUES({q(k)},{js(v)});")

# socials
order = st.get("socialOrder") or ["instagram", "facebook", "tiktok", "telegram"]
for i, p in enumerate(order):
    out.append("INSERT INTO socials(platform,url,sort,enabled,avatar_key,qr_key) VALUES(%s,%s,%d,%s,%s,%s);" % (
        q(p), q((st.get("social") or {}).get(p, "")), i, q((st.get("socialOn") or {}).get(p, True) is not False),
        q(img_key((st.get("pics") or {}).get(p, ""), f"avatar-{p}")), q(img_key((st.get("qr") or {}).get(p, ""), f"qr-{p}"))))

# shipping
assert len(D["ship"]) == 58 and len(WIL) == 58
for i, s in enumerate(D["ship"]):
    out.append(f"INSERT INTO shipping(wilaya_code,wilaya_name,home_price,desk_price) VALUES({i+1},{q(WIL[i])},{s['h']},{s['d']});")

# categories: parents must be inserted before children
cats = D["cats"]
by_id = {c["id"]: c for c in cats}
done, ordered = set(), []
def add(c):
    if c["id"] in done:
        return
    if c.get("parent"):
        add(by_id[c["parent"]])
    done.add(c["id"]); ordered.append(c)
for c in cats:
    add(c)
sort_in_parent = {}
for c in ordered:
    pk = c.get("parent") or ""
    sort_in_parent[pk] = sort_in_parent.get(pk, -1) + 1
    out.append("INSERT INTO categories(id,name,name_en,parent_id,sort,img_key,hidden,is_needs,facets) VALUES(%s,%s,%s,%s,%d,%s,%s,%s,%s);" % (
        q(c["id"]), q(c["name"]), q(c.get("en", "")), q(c.get("parent")), sort_in_parent[pk],
        q(img_key(c.get("img", ""), "cat-" + c["id"])), q(bool(c.get("hidden"))), q(bool(c.get("needs"))), js(c.get("facets", []))))

# products
for p in D["products"]:
    out.append("INSERT INTO products(id,name,brand,price,old_price,stock,size,description,ingredients,usage,colors,sizes,attrs,is_new,is_best,hidden,is_demo,created_at) VALUES(%s,%s,%s,%d,%d,%d,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%d);" % (
        q(p["id"]), q(p["name"]), q(p.get("brand", "")), p["price"], p.get("old", 0), p.get("stock", 0), q(p.get("size", "")),
        q(p.get("desc", "")), q(p.get("ingr", "")), q(p.get("usage", "")), js(p.get("colors", [])), js(p.get("sizes", [])), js(p.get("attrs", {})),
        q(bool(p.get("isNew"))), q(bool(p.get("best"))), q(bool(p.get("hidden"))), q(bool(p.get("demo"))), p.get("ts", 0)))
    for c in p.get("cats", []):
        out.append(f"INSERT INTO product_categories(product_id,category_id) VALUES({q(p['id'])},{q(c)});")
    for v in p.get("variants", []):
        out.append(f"INSERT INTO product_variants(product_id,size,color,stock) VALUES({q(p['id'])},{q(v.get('size',''))},{q(v.get('color',''))},{int(v.get('stock',0))});")
    for i, im in enumerate(p.get("imgs", [])):
        out.append(f"INSERT INTO product_images(product_id,position,image_key) VALUES({q(p['id'])},{i},{q(img_key(im, 'p-' + p['id']))});")

# reviews (approved: they were already public)
for r in D.get("reviews", []):
    out.append("INSERT INTO reviews(product_id,name,quality,service,text,approved) VALUES(%s,%s,%d,%d,%s,1);" % (
        q(r["pid"]), q(r["name"]), r["q"], r["s"], q(r.get("text", ""))))

open(os.path.join(ROOT, "db", "seed.sql"), "w", encoding="utf8").write("\n".join(out) + "\n")
print("seed.sql: %d statements; images extracted: %d files, %d bytes" % (len(out) - 3, len(saved), sum(saved.values())))
